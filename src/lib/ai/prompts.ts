export function buildShortenPrompt(originalDescription: string, wordLimit: number, productName?: string): string {
  return `يرجى اختصار الوصف التالي للمنتج${productName ? ` "${productName}"` : ''}:

الوصف الأصلي:
"""
${originalDescription}
"""

المطلوب:
- صغ ملخصاً فنياً وتجارياً واضحاً ومفيداً يركز على أهم المواصفات الحقيقية المذكورة (مثل القدرة بالواط، السعة، المنافذ، التوافق).
- الطول المستهدف: ما بين ${Math.max(6, Math.round(wordLimit * 0.6))} إلى ${wordLimit} كلمة (لا تختصره بشكل مفرط بكلمة أو اثنتين، بل اجعله وصفاً موجزاً غنياً بالمواصفات الأساسية).
- احذف عبارات الحشو التسويقي مثل "يتميز هذا المنتج الرائع" أو "سارع بالشراء".
- لا تبتكر أي معلومة أو مواصفة لم ترد في النص الأصلي.
- أعد نص الوصف المختصر مباشرة بدون أي مقدمات أو علامات تنصيص.`;
}
